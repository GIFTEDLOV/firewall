import {createClient} from '/tmp/genlayer-sdk/node_modules/genlayer-js/dist/index.js';
import {studionet} from '/tmp/genlayer-sdk/node_modules/genlayer-js/dist/chains/index.js';
import {createHash} from 'node:crypto';
import {writeFileSync,mkdirSync} from 'node:fs';
import {dirname} from 'node:path';
const address=process.env.VERIFIED_GENLAYER_ADDRESS;
const expected=process.env.VERIFIED_SOURCE_SHA256;
const path=process.env.VERIFIED_SOURCE_FILE;
const abiPath=process.env.VERIFIED_SCHEMA_FILE;
if(!/^0x[0-9a-fA-F]{40}$/.test(address??'')||!/^([a-f0-9]{64})$/.test(expected??'')||!path||!abiPath)throw Error('SOURCE_SYNC_CONFIG_INVALID');
const c=createClient({chain:studionet,endpoint:'https://studio.genlayer.com/api'});
const code=await c.getContractCode(address);
const sha=createHash('sha256').update(code).digest('hex');
if(sha!==expected)throw Error('DEPLOYED_SOURCE_PARITY_MISMATCH:'+sha);
const schema=await c.getContractSchema(address);
mkdirSync(dirname(path),{recursive:true});
mkdirSync(dirname(abiPath),{recursive:true});
writeFileSync(path,code);
writeFileSync(abiPath,JSON.stringify(schema,null,2)+'\n');
console.log('STUDIONET_V2_SOURCE_VERIFIED',address,sha,'METHODS',Object.keys(schema.methods).length);
